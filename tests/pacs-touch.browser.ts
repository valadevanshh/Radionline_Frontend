import {chromium, type Page} from 'playwright';
import assert from 'node:assert/strict';

async function main(){
 const browser=await chromium.launch({...(process.platform==='win32'?{channel:'msedge'}:{}),headless:true});
 try{
  const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:1});
  const page=await context.newPage();const errors:string[]=[];
  const image='data:image/svg+xml,'+encodeURIComponent('<svg xmlns="http://www.w3.org/2000/svg" width="600" height="800"><rect width="600" height="800" fill="#777"/><path d="M100 100L500 700M500 100L100 700" stroke="white" stroke-width="15"/></svg>');
  const report={id:'touch-fixture',patientNumber:'SYSTEM-TEST',centerPatientId:'CENTER-TEST',fullName:'Sample Touch Patient',age:35,gender:'Female',radiologyCenterId:'center-test',radiologyCenterName:'Sample Centre',bodyParts:['CHEST PA'],modality:'X-Ray',status:'In Review',claimStatus:'CLAIMED',assignedDoctorId:'doctor-test',studyDate:'2026-11-08',createdAt:'2026-11-08',uploadedImages:[image],findings:'Sample findings.',impression:'Sample impression.',studies:[{id:'study-test',bodyPart:'CHEST PA',reportStatus:'DRAFT',claimedBy:'doctor-test',status:'CLAIMED',findings:'Sample findings.'}]};
  const setup=async(p:Page)=>{
   p.on('pageerror',error=>errors.push(error.message));
   await p.addInitScript(()=>localStorage.setItem('radionline_session_v1',JSON.stringify({role:'SUPER_ADMIN',name:'Sample Admin',email:'sample@example.invalid'})));
   await p.routeWebSocket('**/*',ws=>ws.close());
   await p.route('**/*',route=>{const u=new URL(route.request().url());if(u.host==='127.0.0.1:3100'||u.protocol==='data:')return route.continue();let data:any=[];if(u.pathname.endsWith('/reports/touch-fixture'))data=report;else if(u.pathname.endsWith('/centers'))data=[{id:'center-test',centerName:'Sample Centre'}];return route.fulfill({json:data,headers:{'access-control-allow-origin':'*','access-control-allow-headers':'*','access-control-allow-methods':'*'}});});
   await p.goto('http://127.0.0.1:3100/dashboard/workspace/touch-fixture');
   await p.getByTestId('pacs-viewport-0').waitFor();
   await p.getByTestId('pacs-viewport-0').locator('img').first().evaluate((el:any)=>el.decode());
  };
  await setup(page);
  const viewport=page.getByTestId('pacs-viewport-0');
  const canvas=viewport.locator('div[style*="aspect-ratio"]').first();
  const state=()=>canvas.evaluate(el=>{const m=new DOMMatrixReadOnly(getComputedStyle(el).transform);return {zoom:Math.hypot(m.a,m.b),x:m.e,y:m.f};});
  const cdp=await context.newCDPSession(page);
  const touch=async(type:'touchStart'|'touchMove'|'touchEnd'|'touchCancel',points:{x:number;y:number;id:number}[])=>{
   await cdp.send('Input.dispatchTouchEvent',{type,touchPoints:points.map(point=>({...point,radiusX:6,radiusY:6,force:1}))});
   await page.evaluate(()=>new Promise<void>(resolve=>requestAnimationFrame(()=>resolve())));
  };
  const rect=(await viewport.boundingBox())!;
  const cx=rect.x+rect.width/2,cy=rect.y+rect.height/2;
  await page.getByTitle('Zoom',{exact:true}).click();
  const before=await state();
  await touch('touchStart',[{x:cx,y:cy,id:1}]);
  await touch('touchMove',[{x:cx+40,y:cy+25,id:1}]);
  await touch('touchEnd',[]);
  const panned=await state();
  assert.ok(Math.abs(panned.x-before.x-40)<2);
  assert.ok(Math.abs(panned.y-before.y-25)<2);
  assert.ok(Math.abs(panned.zoom-before.zoom)<0.001);
  assert.ok(await viewport.isVisible());
  console.log('PASS: one finger pans even with Zoom selected, without changing zoom');
  const mid={x:cx+20,y:cy-20};
  await touch('touchStart',[{x:mid.x-35,y:mid.y,id:1}]);
  await touch('touchStart',[{x:mid.x-35,y:mid.y,id:1},{x:mid.x+35,y:mid.y,id:2}]);
  await touch('touchMove',[{x:mid.x-70,y:mid.y,id:1},{x:mid.x+70,y:mid.y,id:2}]);
  const zoomed=await state();
  assert.ok(Math.abs(zoomed.zoom/panned.zoom-2)<0.02);
  assert.ok(Math.abs(zoomed.x-(20-2*(20-panned.x)))<3);
  assert.ok(Math.abs(zoomed.y-(-20-2*(-20-panned.y)))<3);
  // Release the second contact while keeping the first finger on the image.
  await touch('touchEnd',[{x:mid.x+70,y:mid.y,id:2}]);
  const oneRemaining=await state();
  assert.ok(Math.abs(oneRemaining.zoom-zoomed.zoom)<0.001);
  assert.ok(Math.abs(oneRemaining.x-zoomed.x)<2);
  await touch('touchMove',[{x:mid.x-58,y:mid.y+8,id:1}]);
  const afterLift=await state();
  assert.ok(Math.abs(afterLift.x-oneRemaining.x-12)<2);
  assert.ok(Math.abs(afterLift.y-oneRemaining.y-8)<2);
  assert.ok(Math.abs(afterLift.zoom-oneRemaining.zoom)<0.001);
  await touch('touchEnd',[]);
  assert.ok(await viewport.isVisible());
  console.log('PASS: two fingers zoom around their midpoint; lifting one finger continues panning without a jump');
  const afterPinch=await state();
  await touch('touchStart',[{x:cx,y:cy,id:1}]);
  await touch('touchMove',[{x:cx+15,y:cy+10,id:1}]);
  await touch('touchEnd',[]);
  const resumed=await state();
  assert.ok(Math.abs(resumed.zoom-afterPinch.zoom)<0.001);
  assert.ok(Math.abs(resumed.x-afterPinch.x-15)<2);
  assert.ok(Math.abs(resumed.y-afterPinch.y-10)<2);
  // An edge-origin image drag must not turn into a Viewer/Report tab swipe.
  await touch('touchStart',[{x:rect.x+5,y:cy,id:1}]);
  await touch('touchMove',[{x:rect.x+105,y:cy,id:1}]);
  await touch('touchEnd',[]);
  assert.ok(await viewport.isVisible());
  console.log('PASS: panning after pinch stays smooth, including image-edge drags');
  await touch('touchStart',[{x:cx-50,y:cy,id:1}]);
  await touch('touchStart',[{x:cx-50,y:cy,id:1},{x:cx+50,y:cy,id:2}]);
  await touch('touchMove',[{x:cx-180,y:cy,id:1},{x:cx+180,y:cy,id:2}]);
  assert.ok((await state()).zoom<=4.001);
  await touch('touchCancel',[]);
  const cancelled=await state();
  await touch('touchStart',[{x:cx,y:cy,id:1}]);
  await touch('touchMove',[{x:cx-10,y:cy-10,id:1}]);
  await touch('touchEnd',[]);
  assert.ok(Math.abs((await state()).x-cancelled.x+10)<2);
  assert.ok(Math.abs((await state()).zoom-cancelled.zoom)<0.001);
  await page.getByTitle('Reset view',{exact:true}).click();await page.waitForTimeout(100);
  await touch('touchStart',[{x:cx-100,y:cy,id:1}]);
  await touch('touchStart',[{x:cx-100,y:cy,id:1},{x:cx+100,y:cy,id:2}]);
  await touch('touchMove',[{x:cx-1,y:cy,id:1},{x:cx+1,y:cy,id:2}]);
  assert.ok(Math.abs((await state()).zoom-0.4)<0.001);
  await touch('touchCancel',[]);
  console.log('PASS: minimum/maximum zoom limits and cancellation cleanup');
  await page.getByTitle('Reset view',{exact:true}).click();await page.waitForTimeout(100);
  await page.getByTitle('Measure',{exact:true}).click();
  const labels=viewport.getByTestId('viewport-svg-0').locator('text');
  const previousLabels=await labels.count();
  await touch('touchStart',[{x:cx-30,y:cy-30,id:1}]);
  await touch('touchMove',[{x:cx+30,y:cy+30,id:1}]);
  await touch('touchEnd',[]);
  assert.equal(await labels.count(),previousLabels+1);
  const completedLabels=await labels.count();
  await touch('touchStart',[{x:cx-30,y:cy,id:1}]);
  await touch('touchStart',[{x:cx-30,y:cy,id:1},{x:cx+30,y:cy,id:2}]);
  await touch('touchMove',[{x:cx-60,y:cy,id:1},{x:cx+60,y:cy,id:2}]);
  await touch('touchEnd',[]);
  assert.equal(await labels.count(),completedLabels);
  console.log('PASS: explicitly selected measurement tool still works; pinch cancels incomplete drawings');
  const desktop=await browser.newPage({viewport:{width:1400,height:1000}});await setup(desktop);
  const desktopCanvas=desktop.getByTestId('pacs-viewport-0').locator('div[style*="aspect-ratio"]').first();
  const getDesktop=()=>desktopCanvas.evaluate(el=>{const m=new DOMMatrixReadOnly(getComputedStyle(el).transform);return {zoom:Math.hypot(m.a,m.b),x:m.e};});
  await desktop.getByTitle('Move',{exact:true}).click();
  const box=(await desktop.getByTestId('pacs-viewport-0').boundingBox())!;
  await desktop.mouse.move(box.x+box.width/2,box.y+box.height/2);await desktop.mouse.down();
  await desktop.mouse.move(box.x+box.width/2+40,box.y+box.height/2+20,{steps:5});await desktop.mouse.up();
  await desktop.waitForTimeout(100);
  assert.ok(Math.abs((await getDesktop()).x)>5);
  assert.ok(Math.abs((await getDesktop()).zoom-1)<0.01);
  await desktop.mouse.wheel(0,-80);await desktop.waitForTimeout(120);
  assert.ok((await getDesktop()).zoom>1);
  assert.deepEqual(errors,[]);
  console.log('PASS: desktop mouse pan and wheel zoom unchanged; no browser errors. External APIs mocked.');
 }finally{await browser.close();}
}
main().catch(error=>{console.error(error);process.exitCode=1;});
